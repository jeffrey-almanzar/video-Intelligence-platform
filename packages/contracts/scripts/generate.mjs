#!/usr/bin/env node
/**
 * Generates typed contracts for both languages from the JSON Schemas + pipeline.json (ADR-016):
 *   - TypeScript  -> apps/api/src/contracts/generated/
 *   - Pydantic v2 -> services/ai/src/vip_ai/contracts/
 *
 * `--check` regenerates into a temp dir and fails if the committed output is stale (used in CI).
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { compileFromFile } from 'json-schema-to-typescript';

const here = import.meta.dirname;
const pkg = path.resolve(here, '..');
const repo = path.resolve(pkg, '../..');
const check = process.argv.includes('--check');

const HEADER =
  'GENERATED by packages/contracts/scripts/generate.mjs. Do not edit; edit the schemas.';
const schemas = [
  { file: 'stage-job.schema.json', ts: 'stage-job.ts', py: 'stage_job.py' },
  { file: 'progress-event.schema.json', ts: 'progress-event.ts', py: 'progress_event.py' },
];

async function generate(tsDir, pyDir) {
  mkdirSync(tsDir, { recursive: true });
  mkdirSync(pyDir, { recursive: true });
  const schemaDir = path.join(pkg, 'schemas');

  for (const s of schemas) {
    const ts = await compileFromFile(path.join(schemaDir, s.file), {
      cwd: schemaDir,
      bannerComment: `/* ${HEADER} */`,
      additionalProperties: false,
      style: { singleQuote: true, printWidth: 100 },
    });
    writeFileSync(path.join(tsDir, s.ts), ts);

    execFileSync(
      'uv',
      [
        'run',
        '--quiet',
        'datamodel-codegen',
        '--input',
        path.join(schemaDir, s.file),
        '--input-file-type',
        'jsonschema',
        '--output',
        path.join(pyDir, s.py),
        '--output-model-type',
        'pydantic_v2.BaseModel',
        '--target-python-version',
        '3.12',
        '--snake-case-field',
        '--allow-population-by-field-name',
        '--use-annotated',
        '--use-standard-collections',
        '--use-union-operator',
        '--field-constraints',
        '--disable-timestamp',
        '--custom-file-header',
        `# ${HEADER}`,
      ],
      {
        cwd: path.join(repo, 'services/ai'),
        stdio: ['ignore', 'ignore', 'inherit'],
        env: { ...process.env, PYTHONWARNINGS: 'ignore::FutureWarning' },
      },
    );
  }

  const pipeline = JSON.parse(readFileSync(path.join(pkg, 'pipeline.json'), 'utf8'));
  const stages = pipeline.stages;

  writeFileSync(
    path.join(tsDir, 'pipeline.ts'),
    `/* ${HEADER} */
import type { StageName } from './stage-job.js';

export type PipelineStage = {
  readonly name: StageName;
  readonly queue: string;
  readonly attempts: number;
  readonly backoffMs: number;
};

export const PIPELINE_VERSION = ${JSON.stringify(pipeline.version)};

export const PIPELINE_STAGES: readonly PipelineStage[] = ${JSON.stringify(stages, null, 2).replaceAll('"', "'")} as const;

export const PIPELINE_QUEUES: readonly string[] = ${JSON.stringify([...new Set(stages.map((s) => s.queue))]).replaceAll('"', "'")};
`,
  );

  const pyStages = stages
    .map(
      (s) =>
        `    PipelineStage(name="${s.name}", queue="${s.queue}", attempts=${s.attempts}, backoff_ms=${s.backoffMs}),`,
    )
    .join('\n');
  writeFileSync(
    path.join(pyDir, 'pipeline.py'),
    `# ${HEADER}
from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class PipelineStage:
    name: str
    queue: str
    attempts: int
    backoff_ms: int


PIPELINE_VERSION = "${pipeline.version}"

PIPELINE_STAGES: tuple[PipelineStage, ...] = (
${pyStages}
)
`,
  );
  writeFileSync(path.join(pyDir, '__init__.py'), `# ${HEADER}\n`);
}

const tsOut = path.join(repo, 'apps/api/src/contracts/generated');
const pyOut = path.join(repo, 'services/ai/src/vip_ai/contracts');

if (!check) {
  await generate(tsOut, pyOut);
  console.log(
    `Generated contracts:\n  ${path.relative(repo, tsOut)}\n  ${path.relative(repo, pyOut)}`,
  );
} else {
  const tmp = mkdtempSync(path.join(tmpdir(), 'vip-contracts-'));
  const tsTmp = path.join(tmp, 'ts');
  const pyTmp = path.join(tmp, 'py');
  await generate(tsTmp, pyTmp);
  const stale = [];
  for (const [fresh, committed] of [
    [tsTmp, tsOut],
    [pyTmp, pyOut],
  ]) {
    for (const f of readdirSync(fresh)) {
      let current = '';
      try {
        current = readFileSync(path.join(committed, f), 'utf8');
      } catch {
        /* missing file counts as stale */
      }
      if (current !== readFileSync(path.join(fresh, f), 'utf8'))
        stale.push(path.relative(repo, path.join(committed, f)));
    }
  }
  if (stale.length) {
    console.error(
      `Generated contracts are stale. Run \`pnpm --filter @vip/contracts generate\`:\n  ${stale.join('\n  ')}`,
    );
    process.exit(1);
  }
  console.log('Contracts are up to date.');
}
